const j = (a: readonly number[]) => a.map((x) => `+${x}`).join("/");

/** 명시 비중 + **잔량**을 붙여 단계 수(n)만큼의 매도 비중 배열을 만든다.
 *  단계가 몇 개든 동작한다 — 3단계였던 종전 값(33/33)도 33/33/34 로 복원된다. */
const stagePcts = (n: number): number[] => {
  const head = S2_PARAMS.sellStagePcts.slice(0, Math.max(0, n - 1));
  const rest = 100 - head.reduce((s, x) => s + x, 0);
  return [...head, Number(rest.toFixed(4))];
};

